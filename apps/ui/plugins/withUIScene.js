/**
 * Expo config plugin for adding UIScene support for iOS 27+ (iPhone Duo).
 *
 * Apps built with iOS 27 SDK must adopt UIScene lifecycle to launch successfully.
 * This plugin adds UIApplicationSceneManifest to Info.plist and creates a minimal
 * SceneDelegate if needed.
 *
 * Reference: https://developer.apple.com/documentation/technologyoverviews/preparing-your-app-for-iphone-duo
 */

const { withInfoPlist, withAppDelegate } = require("@expo/config-plugins");
const path = require("path");
const fs = require("fs");

const withUISceneManifest = (config) => {
  return withInfoPlist(config, (config) => {
    // Add UIApplicationSceneManifest to enable UIScene lifecycle
    // This is required for iOS 27 SDK apps to launch
    if (!config.modResults.UIApplicationSceneManifest) {
      config.modResults.UIApplicationSceneManifest = {
        UIApplicationSupportsMultipleScenes: true,
        UISceneConfigurations: {
          UIWindowSceneSessionRoleApplication: [
            {
              UISceneConfigurationName: "Default Configuration",
              UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
              UISceneStoryboardFile: "",
            },
          ],
        },
      };
    }
    return config;
  });
};

