/**
 * Main plugin that adds UIScene support to the iOS app.
 * @param {any} config - Expo config object
 * @returns {any} Modified config with UIScene support
 */
function withUIScene(config) {
  // First apply UIApplicationSceneManifest to Info.plist
  config = withUISceneManifest(config);

  // Then ensure AppDelegate is compatible with scenes
  config = withSceneDelegate(config);

  return config;
}

